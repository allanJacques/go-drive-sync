-- Versão inicial do esquema. Depois de aplicada, esta migração não deve ser editada:
-- novas alterações pertencem a V2, V3 etc., mantendo o histórico e os checksums.
-- TEXT no H2 corresponde a VARCHAR grande; TIMESTAMP(9) preserva a precisão do Exposed.
CREATE TABLE accounts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    access_token TEXT NOT NULL,
    refresh_token TEXT NOT NULL,
    token_expiry TIMESTAMP(9) NOT NULL,
    is_default BOOLEAN DEFAULT FALSE NOT NULL,
    last_full_sync TIMESTAMP(9),
    created_at TIMESTAMP(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT accounts_email_unique UNIQUE (email)
);

-- A conta precisa existir; RESTRICT mantém a política de remoção explícita de dependentes.
CREATE TABLE folder_mappings (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id INTEGER NOT NULL,
    drive_folder_id VARCHAR(100) NOT NULL,
    drive_folder_name VARCHAR(255) NOT NULL,
    local_folder_path TEXT NOT NULL,
    sync_direction VARCHAR(20) DEFAULT 'BIDIRECTIONAL' NOT NULL,
    last_sync TIMESTAMP(9),
    enabled BOOLEAN DEFAULT TRUE NOT NULL,
    CONSTRAINT fk_folder_mappings_account_id__id FOREIGN KEY (account_id)
        REFERENCES accounts(id) ON DELETE RESTRICT ON UPDATE RESTRICT
);

-- O nome "timestamp" é minúsculo e delimitado, como na primeira definição do Exposed.
-- mapping_id e error_message aceitam NULL; tamanhos de arquivos usam BIGINT/Long.
CREATE TABLE sync_history (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id INTEGER NOT NULL,
    mapping_id INTEGER,
    drive_file_id VARCHAR(100) NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    file_path TEXT NOT NULL,
    direction VARCHAR(10) NOT NULL,
    status VARCHAR(10) NOT NULL,
    file_size BIGINT NOT NULL,
    "timestamp" TIMESTAMP(9) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    error_message TEXT,
    CONSTRAINT fk_sync_history_account_id__id FOREIGN KEY (account_id)
        REFERENCES accounts(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_sync_history_mapping_id__id FOREIGN KEY (mapping_id)
        REFERENCES folder_mappings(id) ON DELETE RESTRICT ON UPDATE RESTRICT
);
